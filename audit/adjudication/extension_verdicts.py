def classify(extended_text: str, ticker: str) -> tuple[str, str]:
    """回傳 (分類, 理由)。未收錄者為 unreviewed。"""
    for label, table in (("wrong", WRONG), ("correct", CORRECT),
                         ("ambiguous", AMBIGUOUS)):
        hit = table.get(extended_text.strip())
        if hit and hit[0] == ticker:
            return label, hit[1]
    return "unreviewed", ""
